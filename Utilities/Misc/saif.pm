sub entittyrep
{
	my $line = $_;

	if($line =~ /&\#x([a-zA-Z0-9]+)\;/g)
	{
		my $entuni = $1;
		my $entval = $eentity{$entuni};
		$line =~ s/$entuni/$entval/g;
	}
	return 	$line;
}

